import { CALC_DEFAULTS, CALC_DATA_DATE } from "@/lib/calcExtra";

const myRwd = getTrimById("my-rwd");
const myLr = getTrimById("my-lr");
const myL = getTrimById("my-l-awd");

const man = (won) => `${(won / 10000).toLocaleString()}만원`;

/** 취득세 계산(전기차 감면 적용) — 세율 7%, 감면 한도 140만원 */
const ACQ_RATE = 0.07;
const ACQ_EXEMPTION_CAP = 1400000;

function acquisitionTax(priceKrw) {
  const gross = Math.round(priceKrw * ACQ_RATE);
  const cut = Math.min(gross, ACQ_EXEMPTION_CAP);
  return { gross, cut, net: gross - cut };
}

const acqRows = [myRwd, myLr, myL].map((t) => {
  const a = acquisitionTax(t.priceKrw);
  return [
    t.trimFull,
    man(t.priceKrw),
    `${Math.round(a.gross / 10000).toLocaleString()}만원`,
    `-${Math.round(a.cut / 10000).toLocaleString()}만원`,
    a.net === 0 ? "0원" : `약 ${Math.round(a.net / 10000).toLocaleString()}만원`,
  ];
});

